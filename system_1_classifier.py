import base64

from dotenv import load_dotenv
from perplexity import Perplexity

PROMPT = """
You are an image-forensics classifier specializing in AI-generated event posters.

Determine whether the ENTIRE poster was likely generated by an AI image-generation
model, rather than assembled primarily through conventional human graphic design.

Inspect the complete image for these indicators:

1. TYPOGRAPHY:
   - Malformed, merged, or inconsistent letters.
   - Pseudo-text, meaningless symbols, or misspelled words.
   - Text that changes shape or blends unnaturally into illustrations.

2. OBJECTS AND ANATOMY:
   - Distorted hands, fingers, faces, eyes, or limbs.
   - Objects that merge together or have physically impossible shapes.
   - Inconsistent details in clothing, accessories, or equipment.

3. GEOMETRY AND SPATIAL CONSISTENCY:
   - Impossible perspective or object intersections.
   - Inconsistent architecture or repeated patterns.
   - Objects that subtly change structure.

4. LIGHTING AND REFLECTIONS:
   - Conflicting shadow directions.
   - Reflections that do not match surrounding objects.
   - Inconsistent lighting between objects in the same scene.

5. TEXTURES AND DETAILS:
   - Unnaturally smooth or undefined surfaces.
   - Details that dissolve into irregular patterns.
   - Inconsistent hair, fabric, foliage, or skin textures.

6. COMPOSITION:
   - Decorative elements that merge unnaturally.
   - Inconsistent visual styles between elements.
   - Evidence that text, imagery, and decorations were generated
     together as one continuous image.

ALSO CONSIDER SIGNS OF HUMAN DESIGN:
   - Consistent typography and spacing.
   - Precisely aligned text, logos, and graphic elements.
   - Clean vector shapes and structured layouts.
   - Independently placed photographs and illustrations.
   - Consistent margins, grids, and visual hierarchy.

IMPORTANT DISTINCTIONS:

- Your task is to identify FULLY AI-GENERATED posters, not merely
  posters containing AI-generated elements.
- A human-designed poster containing an AI-generated illustration
  should not automatically receive a high score.
- A polished, symmetrical, futuristic, surreal, or unusual design
  is not by itself evidence of AI generation.
- Readable text does not prove human authorship.
- Compression, resizing, and low resolution can create misleading artifacts.
- Do not rely on one suspicious detail. Look for multiple independent
  indicators that reinforce one another.
- Do not invent visual evidence.
- If the evidence is ambiguous, avoid an artificially high or low score.

Return the probability that the entire poster was AI-generated.
"""


def image(image_path):
    with open(image_path, "rb") as image_file:
        encoded_image = base64.b64encode(image_file.read()).decode("utf-8")

    image_data_url = f"data:{"image/jpeg"};base64,{encoded_image}"
    client = Perplexity(timeout=30.0)
    MODEL = "pplx-decider-v1.2"

    # Submit the image and classification question
    response = client.decisions.create(
        model=MODEL,
        state=[
            {
                "type": "image_url",
                "image_url": {
                    "url": image_data_url
                },
            }
        ],
        questions={
            "ai_generated": {
                "type": "noul",
                "instructions": PROMPT,
            }
        },
    )

    # probability of answer being YES
    score = response.answers["ai_generated"].noul

    return score * 100


if __name__ == "__main__":
    load_dotenv()

    ai_score = image("images/ai_image.jpg")
    not_ai_score = image("images/not_ai_image.jpg")

    print(f"AI generation score: {ai_score:.2f}")
    print(f"Not AI generation score: {not_ai_score:.2f}")
